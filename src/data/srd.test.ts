import { describe, expect, it } from 'vitest';
import backgrounds from '../../data/srd/backgrounds.json';
import classes from '../../data/srd/classes.json';
import conditions from '../../data/srd/conditions.json';
import creatures from '../../data/srd/creatures.json';
import features from '../../data/srd/features.json';
import items from '../../data/srd/items.json';
import races from '../../data/srd/races.json';
import spells from '../../data/srd/spells.json';
import subclasses from '../../data/srd/subclasses.json';
import { RefPackSchema, type RefEntry } from '../engine/schema';

/** Generated by `npm run import:srd`. These checks catch a bad pin or mapper change. */
const packs = {
  backgrounds,
  classes,
  conditions,
  creatures,
  features,
  items,
  races,
  spells,
  subclasses,
};
const parsed = Object.fromEntries(
  Object.entries(packs).map(([name, pack]) => [name, RefPackSchema.parse(pack)]),
) as Record<keyof typeof packs, RefEntry[]>;
const all = Object.values(parsed).flat();
const byId = new Map(all.map((entry) => [entry.id, entry]));
const get = <K extends RefEntry['kind']>(kind: K, id: string) => {
  const entry = byId.get(id);
  if (entry?.kind !== kind) throw new Error(`No ${kind} ${id}`);
  return entry as Extract<RefEntry, { kind: K }>;
};

describe('SRD packs', () => {
  it('are valid, SRD-only, and use each id once', () => {
    expect(all.every((entry) => entry.srd && entry.ruleset === '5e-2014')).toBe(true);
    expect(byId.size).toBe(all.length);
    for (const [name, entries] of Object.entries(parsed)) {
      expect(entries.length, name).toBeGreaterThan(0);
    }
  });

  it('only reference ids that exist', () => {
    const references = [
      ...parsed.spells.flatMap((entry) => (entry.kind === 'spell' ? entry.classes : [])),
      ...parsed.classes.flatMap((entry) =>
        entry.kind === 'class' ? entry.features.map((row) => row.featureId) : [],
      ),
      ...parsed.subclasses.flatMap((entry) =>
        entry.kind === 'subclass'
          ? [entry.classId, ...entry.features.map((row) => row.featureId)]
          : [],
      ),
      ...parsed.races.flatMap((entry) =>
        entry.kind === 'race'
          ? [...entry.featureIds, ...(entry.subraceOf ? [entry.subraceOf] : [])]
          : [],
      ),
      ...parsed.backgrounds.flatMap((entry) =>
        entry.kind === 'background' ? entry.featureIds : [],
      ),
    ];
    expect(references.filter((id) => !byId.has(id))).toEqual([]);
  });

  it('has The Fool’s SRD content', () => {
    const bard = get('class', 'class.bard');
    expect(bard).toMatchObject({
      hitDie: 'd8',
      saves: ['DEX', 'CHA'],
      spellcasting: { ability: 'CHA', progression: 'full', ritual: 'known' },
      subclassLevel: 3,
    });
    expect(bard.features).toContainEqual({
      level: 2,
      featureId: 'feature.bard.jack-of-all-trades',
    });
    expect(bard.features).toContainEqual({
      level: 1,
      featureId: 'feature.bard.bardic-inspiration',
    });
    expect(bard.spellcasting?.cantripsKnown?.slice(0, 4)).toEqual([2, 2, 2, 3]);
    expect(bard.spellcasting?.spellsKnown?.slice(0, 4)).toEqual([4, 5, 6, 7]);
    expect(get('subclass', 'subclass.bard.lore').features).toContainEqual({
      level: 3,
      featureId: 'feature.bard.cutting-words',
    });

    expect(get('spell', 'spell.healing-word')).toMatchObject({
      casting: { cost: 'bonus' },
      heal: { dice: '1d4', addCastingMod: true, upcastPerLevel: '1d4' },
      tags: ['healing'],
    });
    expect(get('spell', 'spell.faerie-fire')).toMatchObject({
      save: 'DEX',
      duration: { text: '1 min', seconds: 60, concentration: true },
    });
    expect(get('spell', 'spell.faerie-fire').classes).toContain('class.bard');
    expect(get('spell', 'spell.vicious-mockery').damage).toMatchObject({
      dice: '1d4',
      cantripScaling: true,
      type: 'psychic',
    });

    expect(get('race', 'race.half-elf')).toMatchObject({
      darkvision: 60,
      abilityBonuses: [{ ability: 'CHA', value: 2 }],
      abilityChoices: { count: 2, value: 1, exclude: ['CHA'] },
    });
    expect(get('item', 'item.rapier').weapon).toEqual({
      category: 'martial',
      type: 'melee',
      damage: '1d8',
      damageType: 'piercing',
      properties: ['finesse'],
    });
    expect(get('item', 'item.leather-armor').armor).toMatchObject({
      category: 'light',
      baseAc: 11,
    });
    expect(get('item', 'item.flute').category).toBe('instrument');
    expect(get('item', 'item.disguise-kit').category).toBe('tool');
  });

  it('has the SRD creatures with their statblock numbers', () => {
    expect(parsed.creatures).toHaveLength(334);
    const goblin = get('creature', 'creature.goblin');
    expect(goblin).toMatchObject({
      size: 'small',
      creatureType: 'humanoid (goblinoid)',
      ac: 15,
      acNote: 'leather armor, shield',
      hp: 7,
      hpFormula: '2d6',
      speed: { walk: 30 },
      cr: 0.25,
      xp: 50,
      skills: { stealth: 6 },
      senses: { darkvision: 60, passivePerception: 9 },
    });
    expect(goblin.actions[0]).toMatchObject({
      name: 'Scimitar',
      attackBonus: 4,
      damage: [{ dice: '1d6+2', type: 'slashing' }],
    });
    const dragon = get('creature', 'creature.adult-black-dragon');
    expect(dragon.legendaryActions.length).toBeGreaterThan(0);
    expect(dragon.saves).toMatchObject({ DEX: 7 });
    expect(get('creature', 'creature.mage').acNote).toBe('15 with mage armor');
  });

  it('has every 2014 condition', () => {
    expect(parsed.conditions).toHaveLength(15);
    expect(byId.has('condition.exhaustion')).toBe(true);
  });
});
