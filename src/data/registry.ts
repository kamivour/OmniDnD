import contentBackgrounds from '../../data/content/backgrounds.json';
import contentFeatures from '../../data/content/features.json';
import contentItems from '../../data/content/items.json';
import contentSpells from '../../data/content/spells.json';
import summaries from '../../data/content/summaries.json';
import featureMechanics from '../../data/mechanics/features.json';
import spellMechanics from '../../data/mechanics/spells.json';
import srdBackgrounds from '../../data/srd/backgrounds.json';
import srdClasses from '../../data/srd/classes.json';
import srdConditions from '../../data/srd/conditions.json';
import srdFeatures from '../../data/srd/features.json';
import srdItems from '../../data/srd/items.json';
import srdMagicItems from '../../data/srd/magic-items.json';
import srdRaces from '../../data/srd/races.json';
import srdSpells from '../../data/srd/spells.json';
import srdSubclasses from '../../data/srd/subclasses.json';
import { buildRegistry } from '../engine/registry';
import {
  MechanicsOverlayPackSchema,
  RefPackSchema,
  SummaryOverlayPackSchema,
} from '../engine/schema';

/** Generated by `npm run import:srd`. */
export const srdPacks = {
  backgrounds: srdBackgrounds,
  classes: srdClasses,
  conditions: srdConditions,
  features: srdFeatures,
  items: srdItems,
  magicItems: srdMagicItems,
  races: srdRaces,
  spells: srdSpells,
  subclasses: srdSubclasses,
};

/** Non-SRD entries in our own words (DATA.md §2). */
export const contentPacks = {
  backgrounds: contentBackgrounds,
  features: contentFeatures,
  items: contentItems,
  spells: contentSpells,
};

export const mechanicsPacks = { features: featureMechanics, spells: spellMechanics };

/** All bundled reference data. Throws at load if any pack or overlay is invalid. */
export const registry = buildRegistry(
  [...Object.values(srdPacks), ...Object.values(contentPacks)].map((pack) =>
    RefPackSchema.parse(pack),
  ),
  SummaryOverlayPackSchema.parse(summaries),
  Object.values(mechanicsPacks).flatMap((pack) => MechanicsOverlayPackSchema.parse(pack)),
);
