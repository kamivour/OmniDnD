import contentBackgrounds from '../../data/content/backgrounds.json';
import contentClasses from '../../data/content/classes.json';
import contentFeatures from '../../data/content/features.json';
import contentItems from '../../data/content/items.json';
import contentRaces from '../../data/content/races.json';
import contentSpells from '../../data/content/spells.json';
import contentSubclasses from '../../data/content/subclasses.json';
import summaries from '../../data/content/summaries.json';
import tashaItems from '../../data/content/tasha-items.json';
import xanatharItems from '../../data/content/xanathar-items.json';
import featureMechanics from '../../data/mechanics/features.json';
import itemMechanics from '../../data/mechanics/items.json';
import spellMechanics from '../../data/mechanics/spells.json';
import subclassMechanics from '../../data/mechanics/subclasses.json';
import srdBackgrounds from '../../data/srd/backgrounds.json';
import srdClasses from '../../data/srd/classes.json';
import srdConditions from '../../data/srd/conditions.json';
import srdCreatures from '../../data/srd/creatures.json';
import srdFeatures from '../../data/srd/features.json';
import srdItems from '../../data/srd/items.json';
import srdMagicItems from '../../data/srd/magic-items.json';
import srdRaces from '../../data/srd/races.json';
import srdSpells from '../../data/srd/spells.json';
import srdSubclasses from '../../data/srd/subclasses.json';
import { buildRegistry, characterRegistry } from '../engine/registry';
import { COMMON_REPLICA_PREFIX, REPLICATE_RECIPES } from '../engine/calc/infusions';
import { itemType } from '../engine/catalog';
import {
  type CharacterBuild,
  ItemDefSchema,
  MechanicsOverlayPackSchema,
  RefPackSchema,
  SummaryOverlayPackSchema,
} from '../engine/schema';

/** Generated by `npm run import:srd`. */
export const srdPacks = {
  backgrounds: srdBackgrounds,
  classes: srdClasses,
  conditions: srdConditions,
  creatures: srdCreatures,
  features: srdFeatures,
  items: srdItems,
  magicItems: srdMagicItems,
  races: srdRaces,
  spells: srdSpells,
  subclasses: srdSubclasses,
};

const commonReplicaRecipes = [...srdMagicItems, ...contentItems, ...tashaItems, ...xanatharItems]
  .filter((item) => 'rarity' in item && item.rarity === 'common')
  .map((item) => ItemDefSchema.parse(item))
  .filter((item) => !['potion', 'scroll'].includes(itemType(item)))
  .map(({ id, name }) => ({
    id: `${COMMON_REPLICA_PREFIX}${id.slice('item.'.length)}`,
    name,
    level: 2,
  }));

/** Non-SRD entries in our own words (DATA.md §2). */
export const contentPacks = {
  backgrounds: contentBackgrounds,
  classes: contentClasses,
  features: contentFeatures,
  items: contentItems,
  tashaItems,
  xanatharItems,
  races: contentRaces,
  spells: contentSpells,
  subclasses: contentSubclasses,
  infusionRecipes: [...REPLICATE_RECIPES, ...commonReplicaRecipes].map(({ id, name, level }) => ({
    kind: 'feature',
    id,
    name: `Replicate Magic Item: ${name}`,
    ruleset: '5e-2014',
    source: 'TCE',
    srd: false,
    origin: 'class',
    activation: 'passive',
    summaryReviewed: false,
    summary: {
      effect: `Artificer ${level}+. Learn to replicate ${name}. This is one known infusion. Record the created item in Inventory and count it against your active limit.`,
    },
  })),
};

export const mechanicsPacks = {
  features: featureMechanics,
  items: itemMechanics,
  spells: spellMechanics,
  subclasses: subclassMechanics,
};

/** All bundled reference data. Throws at load if any pack or overlay is invalid. */
export const registry = buildRegistry(
  [...Object.values(srdPacks), ...Object.values(contentPacks)].map((pack) =>
    RefPackSchema.parse(pack),
  ),
  SummaryOverlayPackSchema.parse(summaries),
  Object.values(mechanicsPacks).flatMap((pack) => MechanicsOverlayPackSchema.parse(pack)),
);

/** Bundled data plus one character's custom items. */
export function registryFor(build: Pick<CharacterBuild, 'customItems'>) {
  return characterRegistry(registry, build);
}
